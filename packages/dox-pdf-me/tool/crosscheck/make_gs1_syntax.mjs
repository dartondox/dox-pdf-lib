// Makes lib/src/barcodes/gs1_syntax.dart from the GS1 Syntax Dictionary in
// BWIPP's `gs1process` (node_modules/bwip-js/barcode.ps, after `npm ci`):
//   node make_gs1_syntax.mjs ../../lib/src/barcodes/gs1_syntax.dart
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ps = readFileSync(join(here, 'node_modules/bwip-js/barcode.ps'), 'latin1');
const pkg = JSON.parse(readFileSync(join(here, 'node_modules/bwip-js/package.json'), 'utf8'));

const block = (start, end) => {
  const a = ps.indexOf(start);
  const b = ps.indexOf(end, a);
  return ps.slice(a + start.length, b);
};

// A small reader of the PostScript values in the dictionary.
function tokens(src) {
  const out = [];
  const re = /%[^\n]*|<<|>>|\[|\]|\((?:\\.|[^)\\])*\)|\/[^\s\[\]()<>/]+|[^\s\[\]()<>/]+/g;
  for (const m of src.matchAll(re)) {
    if (!m[0].startsWith('%')) out.push(m[0]);
  }
  return out;
}

function parse(toks) {
  let i = 0;
  const value = () => {
    const t = toks[i++];
    if (t === '<<') {
      const d = {};
      while (toks[i] !== '>>') {
        const k = value();
        d[k] = value();
      }
      i++;
      return d;
    }
    if (t === '[') {
      const a = [];
      while (toks[i] !== ']') a.push(value());
      i++;
      return a;
    }
    if (t.startsWith('(')) return t.slice(1, -1).replace(/\\(.)/g, '$1');
    if (t.startsWith('/')) return t.slice(1);
    if (t === 'true' || t === 'false') return t === 'true';
    if (/^-?\d+$/.test(t)) return Number(t);
    return { op: t };
  };
  // << dict >> (ai) exch dup ... pop, repeated
  const syntax = {};
  while (i < toks.length) {
    const d = value();
    while (toks[i] !== 'pop') {
      const ai = value();
      i += 2; // exch dup
      syntax[ai] = d;
    }
    i++;
  }
  return syntax;
}

const syntax = parse(tokens(block('/gs1syntax <<', '>> readonly def')));
const spec = (d) => [
  d.parts.map((p) => [p.cset, p.min, p.max, p.opt ? 1 : 0, p.linters.join('.')].join(',')).join(' '),
  (d.ex ?? []).join(','),
  (d.req ?? []).map((r) => r.map((alt) => alt.join('+')).join('/')).join(';'),
].join('|');

const names = (start) =>
  tokens(block(start, '] {dup} forall')).filter((t) => t.startsWith('/')).map((t) => t.slice(1));
const cset = (name) => {
  const m = ps.match(new RegExp(`/${name} <<\\s*0 \\(((?:\\\\.|[^)\\\\])*)\\)`));
  return m[1].replace(/\\(.)/g, '$1');
};

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const list = (name, items) => `const String ${name} =\n    ${q(items.join(' '))};\n`;

let out = `// Generated by tool/crosscheck/make_gs1_syntax.mjs from the GS1 Syntax
// Dictionary of BWIPP (bwip-js ${pkg.version}, MIT license, Copyright (c)
// 2004-2026 Terry Burton). Do not edit by hand.

/// AI to its spec: the parts (cset,min,max,optional,linters), the AIs it
/// excludes, and the AIs it requires (alternatives split by /, all of them
/// joined by +, more requirements split by ;), split by |.
const Map<String, String> gs1Syntax = <String, String>{
`;
for (const [ai, d] of Object.entries(syntax)) out += `  ${q(ai)}: ${q(spec(d))},\n`;
out += '};\n\n';
out += `const String gs1Cset82 = ${q(cset('cset82'))};\n`;
out += `const String gs1Cset39 = ${q(cset('cset39'))};\n`;
out += `const String gs1Cset32 = ${q(cset('cset32'))};\n`;
out += `const String gs1Cset64 = ${q(cset('cset64'))};\n\n`;
out += list('gs1Iso3166', names('/iso3166 << ['));
out += list('gs1Iso3166Alpha2', names('/iso3166alpha2 << ['));
out += list('gs1Iso4217', names('/iso4217 << ['));
out += list('gs1MediaTypes', names('/aidcmediatype << ['));
out += list('gs1PackageTypes', names('/packagetype << ['));
writeFileSync(process.argv[2], out);
console.log(`${Object.keys(syntax).length} AIs`);
